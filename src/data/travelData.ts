function tiers(
  days: number,
  prices: [number, number, number, number, number, number],
) {
  const labels = [
    "Solo",
    "Pair",
    "Group of 3",
    "Group of 4",
    "Group of 5",
    "Group of 6",
  ];
  return prices.map((pricePerPersonUsd, index) => ({
    id: `t${index + 1}`,
    label: labels[index],
    travellers: index + 1,
    pricePerPersonUsd,
    days,
  }));
}

